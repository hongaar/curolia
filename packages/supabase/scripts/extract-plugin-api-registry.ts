/**
 * Collects public API exposure from each plugin's `src/api-registry.ts` and generates
 * `api-registry.gen.ts` for the `api` Edge Function.
 *
 * Run via `tsx` from the repo root (see `sync-plugins.mjs`).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../../..");
const pluginsRoot = path.join(repoRoot, "packages", "plugins");
const outPath = path.join(
  repoRoot,
  "packages",
  "api",
  "supabase",
  "functions",
  "api",
  "api-registry.gen.ts",
);

async function main() {
  const entries: unknown[] = [];
  for (const ent of fs.readdirSync(pluginsRoot, { withFileTypes: true })) {
    if (!ent.isDirectory()) continue;
    const file = path.join(pluginsRoot, ent.name, "src", "api-registry.ts");
    if (!fs.existsSync(file)) continue;
    const mod = (await import(pathToFileURL(file).href)) as Record<
      string,
      unknown
    >;
    for (const value of Object.values(mod)) {
      if (!value || typeof value !== "object") continue;
      const o = value as Record<string, unknown>;
      if (typeof o.pluginTypeId !== "string" || !o.pluginTypeId.trim())
        continue;
      if (!o.map && !o.pin) continue;
      entries.push(o);
    }
  }

  const body = `// Generated by packages/supabase/scripts/extract-plugin-api-registry.ts — do not edit.
import type { ApiPluginEntry } from "./lib/_api/app.ts";

export const pluginApiRegistry: readonly ApiPluginEntry[] = ${JSON.stringify(entries, null, 2)};
`;
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, body);
  console.log(
    `extract-plugin-api-registry: ${entries.length} plugin(s) -> ${path.relative(repoRoot, outPath)}`,
  );
}

void main();
